# 训练数据归一化
#
# 目标：把任意形态的训练数据记录（SFT 指令、多轮对话、偏好对、Agent 轨迹、
# 预训练正文…）压成一组稳定列，供画像聚合与后续落库/回读使用。
#
# 形态判定基于真实采样得到的 UltraData 字段（backend/app/data/ultradata_samples/）：
#   UltraInteract_sft : instruction + response                -> sft
#   UltraChat         : data: [str, str, ...]（奇偶交替）      -> chat
#   UltraFeedback     : instruction + completions[].annotations-> preference
#   UltraData-SFT-Agent-2609 : messages(JSON串) + tools        -> agent
#   Ultra-FineWeb     : content + score                       -> pretrain
#   DCAD-2000         : text + 质量统计列                      -> pretrain
#   UltraX-Preview    : raw_content + cleaned_content          -> pretrain
import hashlib
import json
import math
import re
from typing import Any, Dict, List, Optional, Tuple

# ---------------------------------------------------------------------------
# 归一化后的样本格式
# ---------------------------------------------------------------------------
FORMAT_SFT = "sft"
FORMAT_CHAT = "chat"
FORMAT_PREFERENCE = "preference"
FORMAT_AGENT = "agent"
FORMAT_PRETRAIN = "pretrain"
FORMAT_QA = "qa"
FORMAT_OTHER = "other"

FORMAT_LABELS = {
    FORMAT_SFT: "指令微调 (SFT)",
    FORMAT_CHAT: "多轮对话 (Chat)",
    FORMAT_PREFERENCE: "偏好/奖励 (Preference)",
    FORMAT_AGENT: "Agent 轨迹 (Tool-use)",
    FORMAT_PRETRAIN: "预训练语料 (Pretrain)",
    FORMAT_QA: "问答对 (QA)",
    FORMAT_OTHER: "其他 (Other)",
}

# 领域标签关键词（对齐 UltraData 标签体系：SFT/RL/Agent/代码/数学推理/网页语料…）
DOMAIN_RULES: List[Tuple[str, str]] = [
    ("代码", r"code|coding|python|java(script)?|golang|rust|c\+\+|github|algorithm|编程|代码|算法"),
    ("数学推理", r"math|mathematic|algebra|geometry|theorem|equation|数学|几何|方程|计算题"),
    ("推理", r"reason|chain of thought|cot\b|step by step|推理|思考|思维链"),
    ("Agent", r"agent|trajectory|environment|planning|智能体|代理执行"),
    ("工具调用", r"tool[_ ]?call|function[_ ]?call|tools\b|api call|工具调用|函数调用"),
    ("对话", r"chat|dialog|conversation|multi-turn|对话|闲聊|多轮"),
    ("网页语料", r"common crawl|\bcc-?main\b|web corpus|crawl|网页|语料"),
    ("知识问答", r"knowledge|encyclopedia|wikidata|wikipedia|事实|知识|百科"),
    ("翻译", r"translation|translate|翻译"),
    ("写作", r"writing|essay|summar|摘要|写作|续写"),
    ("偏好学习", r"preference|reward|ranking|偏好|奖励"),
    ("合成数据", r"synthetic|generated by|llm-generated|合成|增强"),
    ("安全合规", r"safety|harmful|toxic|refusal|安全|敏感|违规"),
    ("多语言", r"multilingual|multilanguage|多语言"),
]

# 长度分桶（字符数）
LENGTH_BUCKETS = [(0, 64), (64, 256), (256, 1024), (1024, 4096), (4096, None)]
BUCKET_LABELS = ["0-64", "64-256", "256-1k", "1k-4k", "4k+"]

_ZH_RE = re.compile(r"[\u4e00-\u9fff]")
_WORD_RE = re.compile(r"[A-Za-z]+")


def _s(value: Any) -> str:
    """任意值转可读文本（列表/字典拼接，None 归空）"""
    if value is None:
        return ""
    if isinstance(value, str):
        return value
    if isinstance(value, (int, float, bool)):
        return str(value)
    if isinstance(value, (list, tuple)):
        return "\n".join(_s(v) for v in value)
    if isinstance(value, dict):
        return json.dumps(value, ensure_ascii=False)
    return str(value)


def _first(record: Dict[str, Any], *keys: str) -> Any:
    for k in keys:
        v = record.get(k)
        if v not in (None, "", [], {}):
            return v
    return None


def _parse_jsonish(value: Any) -> Any:
    """字段值是 JSON 字符串时解出来（Agent 的 messages 就是 JSON 串列表）"""
    if isinstance(value, str):
        s = value.strip()
        if s[:1] in "[{":
            try:
                return json.loads(s)
            except (json.JSONDecodeError, ValueError):
                return value
        return value
    return value


# ---------------------------------------------------------------------------
# 格式判定
# ---------------------------------------------------------------------------
def detect_format(record: Dict[str, Any]) -> str:
    keys = {k.lower() for k in record}

    # 偏好/奖励：显式 chosen/rejected，或带细粒度标注的 completions
    if "chosen" in keys and "rejected" in keys:
        return FORMAT_PREFERENCE
    if isinstance(record.get("completions"), list):
        return FORMAT_PREFERENCE
    if {"correct_answers", "incorrect_answers"} <= keys:
        return FORMAT_PREFERENCE

    has_tools = bool(_first(record, "tools", "functions", "tool_calls"))
    messages = _first(record, "messages", "conversation", "conversations", "chat")
    if isinstance(messages, str):
        messages = _parse_jsonish(messages)
    # UltraChat 形态：data 是纯字符串列表，奇偶位构成一轮
    data = record.get("data")
    if messages is None and isinstance(data, list) and data and all(
        isinstance(x, str) for x in data
    ):
        messages = data
    if isinstance(messages, list) and messages:
        def _is_tool_msg(m: Any) -> bool:
            if isinstance(m, dict) and m.get("role") in ("tool", "function"):
                return True
            return isinstance(m, str) and '"role":"tool"' in m.lstrip()[:40]

        if has_tools or any(_is_tool_msg(m) for m in messages):
            return FORMAT_AGENT
        return FORMAT_CHAT
    if has_tools:
        return FORMAT_AGENT

    # 问答对（历史 RAG 数据集的 question/answer 形态，保持兼容）
    if (
        _first(record, "question", "query") is not None
        and _first(record, "answer", "answers", "ground_truth", "gold_answer") is not None
        and _first(record, "instruction", "prompt") is None
    ):
        return FORMAT_QA

    # 指令微调
    if _first(record, "instruction", "prompt", "query", "input", "question") is not None and (
        _first(record, "response", "output", "answer", "completion", "target") is not None
    ):
        return FORMAT_SFT

    if _first(record, "text", "content", "raw_content", "cleaned_content", "body", "document") is not None:
        return FORMAT_PRETRAIN

    if _first(record, "question", "query") is not None and _first(record, "answer", "answers") is not None:
        return FORMAT_QA

    return FORMAT_OTHER


# ---------------------------------------------------------------------------
# 内容抽取
# ---------------------------------------------------------------------------
def _extract_messages(record: Dict[str, Any], fmt: str) -> List[Dict[str, str]]:
    raw = _first(record, "messages", "conversation", "conversations", "chat")
    if raw is None and isinstance(record.get("data"), list):
        raw = record.get("data")
    if raw is None:
        return []
    raw = _parse_jsonish(raw)
    if not isinstance(raw, list):
        return []

    out: List[Dict[str, str]] = []
    # Agent 数据集的 messages 是 JSON 字符串列表，先解成 dict 再走结构化分支
    decoded = [
        _parse_jsonish(item) if isinstance(item, str) else item for item in raw
    ]
    if any(isinstance(item, dict) and ("role" in item or "content" in item) for item in decoded):
        raw = decoded
    elif all(isinstance(item, str) for item in raw):
        # UltraChat：纯字符串列表，按 角色=user/assistant 交替展开
        for i, text in enumerate(raw):
            out.append({"role": "user" if i % 2 == 0 else "assistant", "content": text})
        return out

    default_roles = ["user", "assistant"]
    for i, item in enumerate(raw):
        if isinstance(item, dict):
            role = _s(item.get("role") or item.get("from") or item.get("speaker"))
            content = _s(item.get("content") or item.get("value") or item.get("text"))
            if role in ("human", "Human", "user"):
                role = "user"
            elif role in ("gpt", "bot", "assistant", "Assistant"):
                role = "assistant"
            out.append({"role": role or default_roles[i % 2], "content": content})
        elif isinstance(item, str):
            parsed = _parse_jsonish(item)
            if isinstance(parsed, dict) and "role" in parsed:
                out.append({
                    "role": _s(parsed.get("role")),
                    "content": _s(parsed.get("content")),
                })
            else:
                out.append({"role": default_roles[i % 2], "content": item})
    return out


def _count_rounds(messages: List[Dict[str, str]]) -> int:
    """对话轮次 = user 消息数。

    不要用 len(messages)：标准 SFT 样本 [{user},{assistant}] 是 1 轮 2 条消息，
    按条数统计会把「1 轮问答」显示成「2 轮」，量纲错了。
    没有显式 user 角色时（角色名异常/被抹平），退化为按 user/assistant 交替推断。
    """
    if not messages:
        return 0
    user_msgs = sum(1 for m in messages if (m.get("role") or "").lower() == "user")
    if user_msgs:
        return user_msgs
    return (len(messages) + 1) // 2


def _extract_pretrain_text(record: Dict[str, Any]) -> str:
    # cleaned_content（UltraX 精炼后）优先于 raw_content；正文字段按此顺序取首个非空
    value = _first(
        record, "text", "content", "cleaned_content", "body", "document",
        "raw_content", "passage", "corpus",
    )
    return _s(value)


def _to_unit_interval(value: float) -> float:
    """质量分统一到 0-1：不同数据集量纲不一（0-1 / 1-5 / 1-10）"""
    if value <= 1.0:
        return value
    if value <= 5.0:
        return value / 5.0
    if value <= 10.0:
        return value / 10.0
    return 1.0


def _extract_score(record: Dict[str, Any], fmt: str) -> Optional[float]:
    raw = _first(record, "score", "quality_score", "overall_score", "rating")
    if raw is not None:
        try:
            return _to_unit_interval(float(raw))
        except (TypeError, ValueError):
            pass
    # UltraFeedback：从各 completion 的 overall_score 取均值
    if fmt == FORMAT_PREFERENCE and isinstance(record.get("completions"), list):
        scores = []
        for c in record["completions"]:
            if isinstance(c, dict):
                try:
                    scores.append(float(c.get("overall_score")))
                except (TypeError, ValueError):
                    continue
        if scores:
            raw = sum(scores) / len(scores)
            return _to_unit_interval(raw)
    # DCAD-2000：质量统计列推导一个 0-1 分
    for key, low_is_good in (
        ("perplexity_score", True),
        ("lang_id_score", False),
        ("character_repetition_ratio", True),
    ):
        if key in record:
            try:
                v = float(record[key])
            except (TypeError, ValueError):
                continue
            if key == "perplexity_score":
                # 低困惑度更好，经验映射到 0-1
                return 1.0 / (1.0 + math.log1p(max(v, 0.0)) / 4.0)
            if key == "lang_id_score":
                return max(0.0, min(1.0, v))
            return max(0.0, min(1.0, 1.0 - v))
    return None


def detect_language(text: str) -> str:
    if not text:
        return "other"
    zh = len(_ZH_RE.findall(text))
    letters = len(_WORD_RE.findall(text))
    total = zh + letters
    if total == 0:
        return "other"
    zh_ratio = zh / total
    if zh_ratio >= 0.3:
        # 中文占比过半视为中文；字母词数量多则算中英混合
        return "zh" if zh_ratio >= 0.7 or letters / total < 0.35 else "mixed"
    if zh_ratio > 0.02:
        return "mixed"
    return "en"


def extract_labels(record: Dict[str, Any], fmt: str, haystack: str) -> List[str]:
    """领域标签：先读数据自带标签字段，再用关键词规则补足"""
    labels: List[str] = []
    for key in ("labels", "tags", "categories", "category", "domains", "domain", "task", "tasks", "style", "type"):
        value = record.get(key)
        if isinstance(value, str) and value.strip():
            for part in re.split(r"[|,/;]", value):
                part = part.strip()
                if part and len(part) <= 30 and part not in labels:
                    labels.append(part)
        elif isinstance(value, list):
            for item in value:
                item = _s(item).strip()
                if item and len(item) <= 30 and item not in labels:
                    labels.append(item)

    blob = (haystack[:8000] + " " + " ".join(str(k) for k in record.keys())).lower()
    for name, pattern in DOMAIN_RULES:
        if re.search(pattern, blob, re.IGNORECASE) and name not in labels:
            labels.append(name)
    return labels[:12]


# ---------------------------------------------------------------------------
# 主入口
# ---------------------------------------------------------------------------
def normalize_record(record: Dict[str, Any], seq: int = 0) -> Dict[str, Any]:
    """任意训练数据记录 → training_data_records 行字段"""
    if not isinstance(record, dict):
        record = {"text": _s(record)}

    fmt = detect_format(record)
    messages = _extract_messages(record, fmt) if fmt in (FORMAT_CHAT, FORMAT_AGENT) else []

    instruction = ""
    response = ""
    text = ""
    if fmt == FORMAT_PRETRAIN:
        text = _extract_pretrain_text(record)
    elif fmt in (FORMAT_SFT, FORMAT_QA, FORMAT_PREFERENCE):
        instruction = _s(_first(record, "instruction", "prompt", "query", "input", "question"))
        response = _s(
            _first(record, "response", "output", "answer", "answers", "completion", "target", "chosen", "gold_answer")
        )
        if fmt == FORMAT_PREFERENCE and not response:
            # UltraFeedback：取首个 completion 的 response 作为代表性输出
            completions = record.get("completions")
            if isinstance(completions, list) and completions and isinstance(completions[0], dict):
                response = _s(completions[0].get("response"))
    elif fmt in (FORMAT_CHAT, FORMAT_AGENT):
        turns = [m["content"] for m in messages if m.get("content")]
        instruction = turns[0] if turns else ""
        response = turns[-1] if len(turns) > 1 else ""
        text = "\n".join(turns)
    else:
        text = _s(_first(record, "text", "content", "raw", "body")) or _s(
            _first(record, "instruction", "prompt")
        )

    primary = instruction or response or text or ""
    language = detect_language(primary)

    # 去重哈希覆盖全部内容：SFT 的 instruction 常一对多（同一问题多个响应），
    # 只哈希 instruction 会把它们误判成重复样本
    hash_source = "\n".join(
        part for part in (
            instruction,
            response,
            text,
            json.dumps(messages, ensure_ascii=False, sort_keys=True) if messages else "",
        ) if part
    )

    haystack = " ".join([instruction, response, text]) + " " + json.dumps(
        {k: v for k, v in record.items() if isinstance(v, (str, int, float))}, ensure_ascii=False
    )
    labels = extract_labels(record, fmt, haystack)

    char_length = len(primary)
    est_tokens = estimate_tokens(primary)

    # 附加字段：payload 已完整保留，这里只摘画像用得到的结构信息
    metadata = {}
    for key in ("task", "dataset", "source", "domain", "style", "language", "license", "url", "id", "uuid", "uid"):
        value = record.get(key)
        if isinstance(value, (str, int, float)) and value not in (None, ""):
            metadata[key] = value

    return {
        "seq": seq,
        "format": fmt,
        "language": language,
        "labels": labels,
        "instruction": instruction[:20000] or None,
        "response": response[:20000] or None,
        "text": text[:100000] or None,
        "messages": messages or None,
        "score": _extract_score(record, fmt),
        "char_length": char_length,
        "est_tokens": est_tokens,
        "content_hash": content_hash(
            hash_source or json.dumps(record, ensure_ascii=False, sort_keys=True, default=str)
        ),
        "turn_count": len(messages),
        "round_count": _count_rounds(messages),
        "has_tools": bool(_first(record, "tools", "functions", "tool_calls")),
        "payload": record,
        "record_metadata": metadata,
    }


def estimate_tokens(text: str) -> int:
    """粗略 token 估算：英文按 4 字符/token，中文按 1.5 字符/token"""
    if not text:
        return 0
    zh = len(_ZH_RE.findall(text))
    rest = max(len(text) - zh, 0)
    return max(1, int(zh / 1.5 + rest / 4))


def content_hash(text: str) -> str:
    return hashlib.sha1(text.strip().encode("utf-8", "ignore")).hexdigest()
